// Embeds the tree-sitter runtime + C/C++ grammar wasm into a generated TS module
// as base64(gzip(wasm)). This lets the parsers bundle into every target (web,
// desktop, CLI single-file, standalone binaries) with no external .wasm files.
//
// Regenerate with: node scripts/embed-grammars.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.resolve(here, "..", "packages", "core", "src", "lang", "tree-sitter");

const WASM = {
  RUNTIME: "web-tree-sitter/tree-sitter.wasm",
  C: "tree-sitter-wasms/out/tree-sitter-c.wasm",
  CPP: "tree-sitter-wasms/out/tree-sitter-cpp.wasm",
  PYTHON: "tree-sitter-wasms/out/tree-sitter-python.wasm",
};

let out =
  "// AUTO-GENERATED by scripts/embed-grammars.mjs — do not edit by hand.\n" +
  "// base64(gzip(wasm)); decompressed with DecompressionStream at runtime.\n\n";

for (const [name, specifier] of Object.entries(WASM)) {
  const bytes = readFileSync(require.resolve(specifier));
  const encoded = gzipSync(bytes, { level: 9 }).toString("base64");
  out += `export const ${name}_WASM_GZIP_BASE64 =\n  "${encoded}";\n\n`;
  const kb = (encoded.length / 1024).toFixed(0);
  console.log(`${name}: ${kb} KB (base64 of gzip)`);
}

mkdirSync(outDir, { recursive: true });
const target = path.join(outDir, "grammars.generated.ts");
writeFileSync(target, out);
console.log(`wrote ${path.relative(process.cwd(), target)}`);
