// Embeds the tree-sitter runtime + grammar wasm into a generated TS module as
// base64(gzip(wasm)). The module is imported dynamically, so bundlers split it
// into its own chunk: TS/JS-only projects never download it, and only the
// grammars a project actually uses are decompressed and instantiated.
//
// Regenerate with: node scripts/embed-grammars.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.resolve(here, "..", "packages", "core", "src", "lang", "tree-sitter");

const RUNTIME = "web-tree-sitter/tree-sitter.wasm";

// Language id -> grammar wasm. Grammars that are ABI-incompatible with the
// pinned web-tree-sitter (dart=15, elm=12, ql=10, yaml) are intentionally left
// out; see `tree-sitter-wasms`'s out/ directory for the full set.
const GRAMMARS = {
  bash: "tree-sitter-bash.wasm",
  c: "tree-sitter-c.wasm",
  csharp: "tree-sitter-c_sharp.wasm",
  cpp: "tree-sitter-cpp.wasm",
  css: "tree-sitter-css.wasm",
  elisp: "tree-sitter-elisp.wasm",
  elixir: "tree-sitter-elixir.wasm",
  embedded_template: "tree-sitter-embedded_template.wasm",
  go: "tree-sitter-go.wasm",
  html: "tree-sitter-html.wasm",
  java: "tree-sitter-java.wasm",
  json: "tree-sitter-json.wasm",
  kotlin: "tree-sitter-kotlin.wasm",
  lua: "tree-sitter-lua.wasm",
  objc: "tree-sitter-objc.wasm",
  ocaml: "tree-sitter-ocaml.wasm",
  php: "tree-sitter-php.wasm",
  python: "tree-sitter-python.wasm",
  rescript: "tree-sitter-rescript.wasm",
  ruby: "tree-sitter-ruby.wasm",
  rust: "tree-sitter-rust.wasm",
  scala: "tree-sitter-scala.wasm",
  solidity: "tree-sitter-solidity.wasm",
  swift: "tree-sitter-swift.wasm",
  systemrdl: "tree-sitter-systemrdl.wasm",
  tlaplus: "tree-sitter-tlaplus.wasm",
  toml: "tree-sitter-toml.wasm",
  vue: "tree-sitter-vue.wasm",
  zig: "tree-sitter-zig.wasm",
};

function encoded(specifier) {
  const base64 = gzipSync(readFileSync(require.resolve(specifier)), { level: 9 }).toString("base64");
  return base64;
}

let out =
  "// AUTO-GENERATED by scripts/embed-grammars.mjs — do not edit by hand.\n" +
  "// base64(gzip(wasm)); decompressed with DecompressionStream at runtime.\n\n";
out += `export const RUNTIME_WASM_GZIP_BASE64 =\n  "${encoded(RUNTIME)}";\n\n`;

out += "export const GRAMMARS: Record<string, string> = {\n";
let total = 0;
for (const [id, file] of Object.entries(GRAMMARS)) {
  const base64 = encoded(`tree-sitter-wasms/out/${file}`);
  total += base64.length;
  out += `  ${id}: "${base64}",\n`;
  console.log(`${id.padEnd(18)} ${(base64.length / 1024).toFixed(0)} KB`);
}
out += "};\n";

mkdirSync(outDir, { recursive: true });
const target = path.join(outDir, "grammars.generated.ts");
writeFileSync(target, out);
console.log(`\n${Object.keys(GRAMMARS).length} grammars, ${(total / 1048576).toFixed(1)} MB base64 total`);
console.log(`wrote ${path.relative(process.cwd(), target)}`);
